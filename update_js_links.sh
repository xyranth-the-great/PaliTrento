#!/bin/bash
# Update JS links for clean URLs (directory-based)

js_files=(
  "js/home.js"
  "js/ui.js"
  "js/register-business.js"
  "js/auth.js"
  "js/settings.js"
  "js/chat.js"
  "js/business.js"
  "js/standee.js"
  "js/dashboard.js"
  "js/store-setup.js"
  "js/explore.js"
  "js/admin-verification.js"
  "js/products.js"
  "js/product-detail.js"
  "js/register.js"
  "js/login.js"
  "js/verify.js"
