    sed -i 's|"settings\.html"|"/settings/"|g' "$f"
    sed -i 's|"forgot-password\.html"|"/forgot-password/"|g' "$f"
    sed -i 's|"reset-password\.html"|"/reset-password/"|g' "$f"
    sed -i 's|"terms-and-agreement\.html"|"/terms-and-agreement/"|g' "$f"
    
    # Also handle single quotes
    sed -i "s|'index\.html'|'/'|g" "$f"
    sed -i "s|'explore\.html'|'/explore/'|g" "$f"
    sed -i "s|'map\.html'|'/map/'|g" "$f"
    sed -i "s|'products\.html'|'/products/'|g" "$f"
    sed -i "s|'business\.html'|'/business/'|g" "$f"
    sed -i "s|'register\.html'|'/register/'|g" "$f"
    sed -i "s|'login\.html'|'/login/'|g" "$f"
    sed -i "s|'account\.html'|'/account/'|g" "$f"
    sed -i "s|'verify\.html'|'/verify/'|g" "$f"
    sed -i "s|'register-business\.html'|'/register-business/'|g" "$f"
    sed -i "s|'store-setup\.html'|'/store-setup/'|g" "$f"
    sed -i "s|'dashboard\.html'|'/dashboard/'|g" "$f"
    sed -i "s|'chat\.html'|'/chat/'|g" "$f"
    sed -i "s|'admin\.html'|'/admin/'|g" "$f"
    sed -i "s|'admin-verification\.html'|'/admin-verification/'|g" "$f"
    sed -i "s|'admin-prices\.html'|'/admin-prices/'|g" "$f"
    sed -i "s|'admin-reports\.html'|'/admin-reports/'|g" "$f"
    sed -i "s|'product-detail\.html'|'/product-detail/'|g" "$f"
    sed -i "s|'standee\.html'|'/standee/'|g" "$f"
    sed -i "s|'orders\.html'|'/orders/'|g" "$f"
    sed -i "s|'settings\.html'|'/settings/'|g" "$f"
    sed -i "s|'forgot-password\.html'|'/forgot-password/'|g" "$f"
    sed -i "s|'reset-password\.html'|'/reset-password/'|g" "$f"
