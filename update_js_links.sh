    sed -i 's|"store-setup\.html"|"/store-setup/"|g' "$f"
    sed -i 's|"dashboard\.html"|"/dashboard/"|g' "$f"
    sed -i 's|"chat\.html"|"/chat/"|g' "$f"
    sed -i 's|"admin\.html"|"/admin/"|g' "$f"
    sed -i 's|"admin-verification\.html"|"/admin-verification/"|g' "$f"
    sed -i 's|"admin-prices\.html"|"/admin-prices/"|g' "$f"
